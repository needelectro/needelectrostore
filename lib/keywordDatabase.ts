// Helper queries for admin and SEO views
export function getKeywordsByCluster(cluster: string): KeywordEntry[] {
  return MASTER_KEYWORD_DATABASE.filter(k => k.topicCluster.toLowerCase().includes(cluster.toLowerCase()));
}

export function getKeywordsByUrl(url: string): KeywordEntry[] {
  return MASTER_KEYWORD_DATABASE.filter(k => k.targetUrl === url);
}

export function getKeywordsBySourceCategory(category: KeywordSourceCategory): KeywordEntry[] {
  return MASTER_KEYWORD_DATABASE.filter(k => k.sourceCategory === category);
}

export function getKeywordsByPriority(priority: OptimizationPriority): KeywordEntry[] {
  return MASTER_KEYWORD_DATABASE.filter(k => k.priority === priority);
}
